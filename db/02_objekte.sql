-- Folge KIL_<T>_SEQ und Trigger KIL_<T>_BI vergeben die ID (keine Identity-Spalten).
-- Geometrien: SRID 8307 (WGS 84), zweidimensional (Länge, Breite), Toleranz 0,05 m.
-- Der Eintrag in USER_SDO_GEOM_METADATA muss vor dem Spatial-Index da sein.
-- ============================================================================

-- Folgen

CREATE SEQUENCE KIL_SITZUNG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE
/

CREATE SEQUENCE KIL_ZUSTAND_SEQ START WITH 1 INCREMENT BY 1 NOCACHE
/

CREATE SEQUENCE KIL_SCHALTER_SEQ START WITH 1 INCREMENT BY 1 CACHE 50
/

CREATE SEQUENCE KIL_PROTOKOLL_SEQ START WITH 1 INCREMENT BY 1 CACHE 20
/

-- Trigger

CREATE OR REPLACE TRIGGER KIL_SITZUNG_BI
BEFORE INSERT ON KIL_SITZUNG
FOR EACH ROW
WHEN (NEW.SITZUNG_ID IS NULL)
BEGIN
  :NEW.SITZUNG_ID := KIL_SITZUNG_SEQ.NEXTVAL;
END;
/

