  UMRISS          MDSYS.SDO_GEOMETRY,
  LAENGE_KM       NUMBER(5,1),
  BREITE_M        NUMBER(5),
  AA_NAH          NUMBER(3,2),
  AA_FERN         NUMBER(3,2),
  FLAECHE_KM2     NUMBER(8,2),
