  CONSTRAINT KIL_LAUF_STUNDEN_CK CHECK (SIM_STUNDEN IS NULL OR SIM_STUNDEN >= 0),
  CONSTRAINT KIL_LAUF_RIFT_CK CHECK (RIFTZONE IS NULL OR RIFTZONE IN ('OST','SUEDWEST')),
