  MARKE_JAHR      CHAR(1)            DEFAULT 'L' NOT NULL,
  MARKE_WEG       CHAR(1)            DEFAULT 'A' NOT NULL,
  CONSTRAINT KIL_STROM_PK PRIMARY KEY (STROM_ID),
  CONSTRAINT KIL_STROM_NAME_UK UNIQUE (NAME),
