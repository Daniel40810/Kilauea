  MESSUNGEN       NUMBER(6),
  CONSTRAINT KIL_LAUF_PK PRIMARY KEY (LAUF_ID),
  CONSTRAINT KIL_LAUF_SITZUNG_FK FOREIGN KEY (SITZUNG_ID) REFERENCES KIL_SITZUNG (SITZUNG_ID) ON DELETE SET NULL,
