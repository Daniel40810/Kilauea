CREATE TABLE KIL_ORT (
  ORT_ID          NUMBER(10)         NOT NULL,
  SCHLUESSEL      VARCHAR2(20)       NOT NULL,
  NAME            VARCHAR2(80 CHAR)  NOT NULL,
  ART             VARCHAR2(10)       NOT NULL,
  BREITE          NUMBER(9,6)        NOT NULL,
  LAENGE          NUMBER(10,6)       NOT NULL,
  GEOM            MDSYS.SDO_GEOMETRY,
  HOEHE_M         NUMBER(6,1),
  BLICK_GIER      NUMBER(5,1),
  BLICK_NEIGUNG   NUMBER(4,1),
  BLICK_ABSTAND   NUMBER(7),
  KURZTEXT        VARCHAR2(400 CHAR),
  TAFEL           VARCHAR2(1500 CHAR),
  MARKE_LAGE      CHAR(1)            DEFAULT 'L' NOT NULL,
  MARKE_HOEHE     CHAR(1)            DEFAULT 'M' NOT NULL,
  CONSTRAINT KIL_ORT_PK PRIMARY KEY (ORT_ID),
  CONSTRAINT KIL_ORT_SCHLUESSEL_UK UNIQUE (SCHLUESSEL),
  CONSTRAINT KIL_ORT_SCHLUESSEL_CK CHECK (REGEXP_LIKE(SCHLUESSEL, '^[A-Z][A-Z0-9_]*$')),
  CONSTRAINT KIL_ORT_ART_CK CHECK (ART IN ('CALDERA','KRATER','KLIPPE','ROEHRE','KEGEL','KUESTE','PALI','WUESTE','VULKAN','GEBIET')),
  CONSTRAINT KIL_ORT_BREITE_CK CHECK (BREITE BETWEEN 18.8 AND 20.4),
  CONSTRAINT KIL_ORT_LAENGE_CK CHECK (LAENGE BETWEEN -156.2 AND -154.6),
  CONSTRAINT KIL_ORT_HOEHE_CK CHECK (HOEHE_M IS NULL OR HOEHE_M BETWEEN -100 AND 4300),
  CONSTRAINT KIL_ORT_GIER_CK CHECK (BLICK_GIER IS NULL OR BLICK_GIER BETWEEN -360 AND 360),
  CONSTRAINT KIL_ORT_NEIGUNG_CK CHECK (BLICK_NEIGUNG IS NULL OR BLICK_NEIGUNG BETWEEN -90 AND 90),
  CONSTRAINT KIL_ORT_ABSTAND_CK CHECK (BLICK_ABSTAND IS NULL OR BLICK_ABSTAND BETWEEN 0 AND 400000),
  CONSTRAINT KIL_ORT_MARKE_LAGE_CK CHECK (MARKE_LAGE IN ('M','L','A','G')),
  CONSTRAINT KIL_ORT_MARKE_HOEHE_CK CHECK (MARKE_HOEHE IN ('M','L','A','G'))
)
/

CREATE TABLE KIL_KRATER (
  KRATER_ID       NUMBER(10)         NOT NULL,
  NAME            VARCHAR2(60 CHAR)  NOT NULL,
  ART             VARCHAR2(12)       NOT NULL,
  ORT_ID          NUMBER(10),
  MITTE           MDSYS.SDO_GEOMETRY,
  RAND            MDSYS.SDO_GEOMETRY,
  TIEFE_M         NUMBER(6,1),
  LAENGE_M        NUMBER(6),
  BREITE_M        NUMBER(6),
  FLAECHE_HA      NUMBER(8,1),
  ENTSTANDEN      NUMBER(4),
  KURZTEXT        VARCHAR2(400 CHAR),
  MARKE_LAGE      CHAR(1)            DEFAULT 'L' NOT NULL,
  MARKE_FORM      CHAR(1)            DEFAULT 'A' NOT NULL,
  CONSTRAINT KIL_KRATER_PK PRIMARY KEY (KRATER_ID),
  CONSTRAINT KIL_KRATER_NAME_UK UNIQUE (NAME),
  CONSTRAINT KIL_KRATER_ORT_FK FOREIGN KEY (ORT_ID) REFERENCES KIL_ORT (ORT_ID) ON DELETE SET NULL,
  CONSTRAINT KIL_KRATER_ART_CK CHECK (ART IN ('CALDERA','KRATER','GRUBENKRATER','KEGELKRATER')),
  CONSTRAINT KIL_KRATER_TIEFE_CK CHECK (TIEFE_M IS NULL OR TIEFE_M BETWEEN 0 AND 2000),
  CONSTRAINT KIL_KRATER_MASSE_CK CHECK (LAENGE_M IS NULL OR BREITE_M IS NULL OR (BREITE_M > 0 AND LAENGE_M >= BREITE_M)),
  CONSTRAINT KIL_KRATER_FLAECHE_CK CHECK (FLAECHE_HA IS NULL OR FLAECHE_HA > 0),
  CONSTRAINT KIL_KRATER_JAHR_CK CHECK (ENTSTANDEN IS NULL OR ENTSTANDEN BETWEEN 1000 AND 2100),
  CONSTRAINT KIL_KRATER_MARKE_LAGE_CK CHECK (MARKE_LAGE IN ('M','L','A','G')),
  CONSTRAINT KIL_KRATER_MARKE_FORM_CK CHECK (MARKE_FORM IN ('M','L','A','G'))
)
/

CREATE TABLE KIL_STROM (
