  CONSTRAINT KIL_LAUF_LAENGE_CK CHECK (LAENGE_M IS NULL OR LAENGE_M > 0),
  CONSTRAINT KIL_LAUF_BEBEN_CK CHECK (BEBEN IS NULL OR BEBEN >= 0),
  CONSTRAINT KIL_LAUF_MESSUNGEN_CK CHECK (MESSUNGEN IS NULL OR MESSUNGEN >= 0)
)
/

CREATE TABLE KIL_BEBEN (
  BEBEN_ID        NUMBER(12)         NOT NULL,
  LAUF_ID         NUMBER(10)         NOT NULL,
  SIM_STUNDE      NUMBER(9,3)        NOT NULL,
  STAERKE         NUMBER(3,1)        NOT NULL,
