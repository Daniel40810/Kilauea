-- Geschichte: KIL_DREHBUCH, KIL_KAPITEL (Grunddaten), KIL_LAUF, KIL_BEBEN, KIL_MESSUNG (schreibt die App)
-- Aufbau wie 01: <TABELLE>_ID, _PK / _FK / _UK / _CK, Merker 'J'/'N', Kommentar an jeder Spalte.
-- Marken der Herkunft wie im Werkbuch: M gemessen, L belegt, A abgeleitet, G gestaltet.
-- Reihenfolge: 04 Tabellen, 05 Folgen, Trigger, Indizes, Spatial, Paket KIL_WISSEN, 06 Grunddaten.
