CREATE TABLE KIL_DREHBUCH (
  DREHBUCH_ID     NUMBER(10)         NOT NULL,
  SCHLUESSEL      VARCHAR2(20)       NOT NULL,
  TITEL           VARCHAR2(120 CHAR) NOT NULL,
  ZEITRAUM        VARCHAR2(20 CHAR),
  DATUM_VON       DATE,
  DATUM_BIS       DATE,
  ORT_ID          NUMBER(10),
  KURZTEXT        VARCHAR2(600 CHAR),
  KAPITEL         NUMBER(2),
  CONSTRAINT KIL_DREHBUCH_PK PRIMARY KEY (DREHBUCH_ID),
  CONSTRAINT KIL_DREHBUCH_SCHLUESSEL_UK UNIQUE (SCHLUESSEL),
  CONSTRAINT KIL_DREHBUCH_ORT_FK FOREIGN KEY (ORT_ID) REFERENCES KIL_ORT (ORT_ID) ON DELETE SET NULL,
  CONSTRAINT KIL_DREHBUCH_DATUM_CK CHECK (DATUM_BIS IS NULL OR DATUM_VON IS NULL OR DATUM_BIS >= DATUM_VON),
  CONSTRAINT KIL_DREHBUCH_KAPITEL_CK CHECK (KAPITEL IS NULL OR KAPITEL BETWEEN 1 AND 99)
)
/

CREATE TABLE KIL_KAPITEL (
  KAPITEL_ID      NUMBER(10)         NOT NULL,
  DREHBUCH_ID     NUMBER(10)         NOT NULL,
  NR              NUMBER(2)          NOT NULL,
  DATUM_TEXT      VARCHAR2(80 CHAR),
  DATUM_VON       DATE,
  DATUM_BIS       DATE,
  TITEL           VARCHAR2(120 CHAR) NOT NULL,
  TEXT            VARCHAR2(2000 CHAR),
  SIM_STUNDEN     NUMBER(9,2),
  TEMPO           VARCHAR2(40 CHAR),
  TEMPO_FAKTOR    NUMBER(9),
  CONSTRAINT KIL_KAPITEL_PK PRIMARY KEY (KAPITEL_ID),
  CONSTRAINT KIL_KAPITEL_DREHBUCH_FK FOREIGN KEY (DREHBUCH_ID) REFERENCES KIL_DREHBUCH (DREHBUCH_ID) ON DELETE CASCADE,
  CONSTRAINT KIL_KAPITEL_NR_UK UNIQUE (DREHBUCH_ID, NR),
  CONSTRAINT KIL_KAPITEL_NR_CK CHECK (NR BETWEEN 1 AND 99),
  CONSTRAINT KIL_KAPITEL_DATUM_CK CHECK (DATUM_BIS IS NULL OR DATUM_VON IS NULL OR DATUM_BIS >= DATUM_VON),
  CONSTRAINT KIL_KAPITEL_STUNDEN_CK CHECK (SIM_STUNDEN IS NULL OR SIM_STUNDEN >= 0),
  CONSTRAINT KIL_KAPITEL_TEMPO_CK CHECK (TEMPO_FAKTOR IS NULL OR TEMPO_FAKTOR > 0)
)
/

CREATE TABLE KIL_LAUF (
