  CONSTRAINT KIL_STROM_ART_CK CHECK (ART IN ('STROM','FLAECHE')),
  CONSTRAINT KIL_STROM_JAHR_CK CHECK (JAHR_VON BETWEEN 1000 AND 2100 AND (JAHR_BIS IS NULL OR JAHR_BIS >= JAHR_VON)),
  CONSTRAINT KIL_STROM_MODELL_CK CHECK (JAHR_MODELL IS NULL OR JAHR_MODELL BETWEEN JAHR_VON AND NVL(JAHR_BIS, JAHR_VON)),
  CONSTRAINT KIL_STROM_LAENGE_CK CHECK (LAENGE_KM IS NULL OR LAENGE_KM > 0),
  CONSTRAINT KIL_STROM_BREITE_CK CHECK (BREITE_M IS NULL OR BREITE_M > 0),
  CONSTRAINT KIL_STROM_AA_CK CHECK ((AA_NAH IS NULL OR AA_NAH BETWEEN 0 AND 1) AND (AA_FERN IS NULL OR AA_FERN BETWEEN 0 AND 1)),
  CONSTRAINT KIL_STROM_FLAECHE_CK CHECK (FLAECHE_KM2 IS NULL OR FLAECHE_KM2 >= 0),
  CONSTRAINT KIL_STROM_MARKE_JAHR_CK CHECK (MARKE_JAHR IN ('M','L','A','G')),
  CONSTRAINT KIL_STROM_MARKE_WEG_CK CHECK (MARKE_WEG IN ('M','L','A','G'))
)
/

