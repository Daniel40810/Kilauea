-- ============================================================================
-- Kīlauea, Phase 16a: Tabellen für den Betrieb im Schema KILAUEA (Präfix KIL_)
-- Aufbau wie Kneiphof (KNH_) und Heidelberg (HEI_): Präfix je Projekt, <TABELLE>_ID,
-- _PK / _FK / _UK / _CK je Tabelle, Merker als 'J'/'N', Kommentar an jeder Spalte.
-- Jede Anweisung endet mit einer Zeile "/". Das Skript kann beliebig oft laufen:
-- was es schon gibt, meldet der Einrichter als "vorhanden" und lässt es, wie es ist.
-- Reihenfolge: 01 Tabellen, 02 Folgen, Trigger, Indizes, Spatial, 03 Paket KIL_API.
-- Zeichensatz der Datei: UTF-8 (Namen mit ʻokina und Makron).
-- Phase 16b ergänzt 04 (Tabellen für Wissen und Geschichte), 05 (Objekte, Paket KIL_WISSEN) und 06 (Grunddaten).
-- ============================================================================

CREATE TABLE KIL_SITZUNG (
  SITZUNG_ID      NUMBER(10)        NOT NULL,
  GESTARTET       TIMESTAMP(6)      DEFAULT LOCALTIMESTAMP NOT NULL,
  BEENDET         TIMESTAMP(6),
  DAUER_S         NUMBER(8),
  RECHNER         VARCHAR2(80 CHAR),
  BENUTZER        VARCHAR2(60 CHAR),
  APP_VERSION     VARCHAR2(20 CHAR),
  JAVA_VERSION    VARCHAR2(40 CHAR),
  GRAFIK          VARCHAR2(160 CHAR),
  OPENGL          VARCHAR2(80 CHAR),
  KERNE           NUMBER(3),
  SPEICHER_MAX_MB NUMBER(7),
  FENSTER_B       NUMBER(5),
  FENSTER_H       NUMBER(5),
  QUALITAET       VARCHAR2(12 CHAR),
  ZUSTAND_GELADEN CHAR(1)           DEFAULT 'N' NOT NULL,
  BILDER_S        NUMBER(5,1),
  MS_GPU          NUMBER(6,1),
  MS_CPU          NUMBER(6,1),
  SPEICHER_MB     NUMBER(7),
  CONSTRAINT KIL_SITZUNG_PK PRIMARY KEY (SITZUNG_ID),
  CONSTRAINT KIL_SITZUNG_GELADEN_CK CHECK (ZUSTAND_GELADEN IN ('J','N')),
  CONSTRAINT KIL_SITZUNG_DAUER_CK CHECK (DAUER_S IS NULL OR DAUER_S >= 0),
  CONSTRAINT KIL_SITZUNG_BILDER_CK CHECK (BILDER_S IS NULL OR BILDER_S BETWEEN 0 AND 9999)
)
/

CREATE TABLE KIL_ZUSTAND (
  ZUSTAND_ID      NUMBER(10)        NOT NULL,
  ART             VARCHAR2(8)       NOT NULL,
  NAME            VARCHAR2(60 CHAR) NOT NULL,
  GESPEICHERT     TIMESTAMP(6)      DEFAULT LOCALTIMESTAMP NOT NULL,
  SITZUNG_ID      NUMBER(10),
  MODUS           VARCHAR2(8)       DEFAULT 'FLUG' NOT NULL,
  DREHPUNKT_X     NUMBER(10,2)      NOT NULL,
  DREHPUNKT_Y     NUMBER(9,2)       NOT NULL,
  DREHPUNKT_Z     NUMBER(10,2)      NOT NULL,
  GIER            NUMBER(6,2)       NOT NULL,
  NEIGUNG         NUMBER(5,2)       NOT NULL,
  ABSTAND         NUMBER(9,2)       NOT NULL,
  GEOM            MDSYS.SDO_GEOMETRY,
  TAG             NUMBER(3),
  STUNDE          NUMBER(6,3),
  ZEITRAFFER      NUMBER(1),
  DUNST           NUMBER(3),
  WIND_MS         NUMBER(4,1),
  WIND_RICHTUNG   NUMBER(3),
  SWELL_M         NUMBER(3,1),
  SWELL_S         NUMBER(4,1),
  QUALITAET       VARCHAR2(12 CHAR),
  BELICHTUNG      NUMBER(3,1),
  CONSTRAINT KIL_ZUSTAND_PK PRIMARY KEY (ZUSTAND_ID),
  CONSTRAINT KIL_ZUSTAND_SITZUNG_FK FOREIGN KEY (SITZUNG_ID) REFERENCES KIL_SITZUNG (SITZUNG_ID) ON DELETE SET NULL,
  CONSTRAINT KIL_ZUSTAND_ART_CK CHECK (ART IN ('AUTO','ANSICHT')),
  CONSTRAINT KIL_ZUSTAND_MODUS_CK CHECK (MODUS IN ('FLUG','KREISEN','GEHEN')),
  CONSTRAINT KIL_ZUSTAND_X_CK CHECK (DREHPUNKT_X BETWEEN -400000 AND 400000),
  CONSTRAINT KIL_ZUSTAND_Y_CK CHECK (DREHPUNKT_Y BETWEEN -7000 AND 200000),
  CONSTRAINT KIL_ZUSTAND_Z_CK CHECK (DREHPUNKT_Z BETWEEN -400000 AND 400000),
  CONSTRAINT KIL_ZUSTAND_GIER_CK CHECK (GIER >= 0 AND GIER < 360),
  CONSTRAINT KIL_ZUSTAND_NEIGUNG_CK CHECK (NEIGUNG BETWEEN -90 AND 90),
  CONSTRAINT KIL_ZUSTAND_ABSTAND_CK CHECK (ABSTAND BETWEEN 0 AND 400000),
  CONSTRAINT KIL_ZUSTAND_TAG_CK CHECK (TAG IS NULL OR TAG BETWEEN 1 AND 365),
  CONSTRAINT KIL_ZUSTAND_STUNDE_CK CHECK (STUNDE IS NULL OR (STUNDE >= 0 AND STUNDE < 24)),
  CONSTRAINT KIL_ZUSTAND_RAFFER_CK CHECK (ZEITRAFFER IS NULL OR ZEITRAFFER BETWEEN 0 AND 4),
  CONSTRAINT KIL_ZUSTAND_DUNST_CK CHECK (DUNST IS NULL OR DUNST BETWEEN 0 AND 100),
  CONSTRAINT KIL_ZUSTAND_WIND_CK CHECK (WIND_MS IS NULL OR WIND_MS BETWEEN 0 AND 16),
  CONSTRAINT KIL_ZUSTAND_RICHTUNG_CK CHECK (WIND_RICHTUNG IS NULL OR WIND_RICHTUNG BETWEEN 0 AND 359),
  CONSTRAINT KIL_ZUSTAND_SWELL_M_CK CHECK (SWELL_M IS NULL OR SWELL_M BETWEEN 0 AND 4),
  CONSTRAINT KIL_ZUSTAND_SWELL_S_CK CHECK (SWELL_S IS NULL OR SWELL_S BETWEEN 8 AND 20),
  CONSTRAINT KIL_ZUSTAND_QUALITAET_CK CHECK (QUALITAET IS NULL OR QUALITAET IN ('NIEDRIG','MITTEL','HOCH','ULTRA')),
  CONSTRAINT KIL_ZUSTAND_BELICHTUNG_CK CHECK (BELICHTUNG IS NULL OR BELICHTUNG BETWEEN -2 AND 2)
)
/

CREATE TABLE KIL_SCHALTER (
  SCHALTER_ID     NUMBER(10)        NOT NULL,
  ZUSTAND_ID      NUMBER(10)        NOT NULL,
  NAME            VARCHAR2(60)      NOT NULL,
  WERT            VARCHAR2(80 CHAR),
  CONSTRAINT KIL_SCHALTER_PK PRIMARY KEY (SCHALTER_ID),
  CONSTRAINT KIL_SCHALTER_ZUSTAND_FK FOREIGN KEY (ZUSTAND_ID) REFERENCES KIL_ZUSTAND (ZUSTAND_ID) ON DELETE CASCADE,
  CONSTRAINT KIL_SCHALTER_NAME_UK UNIQUE (ZUSTAND_ID, NAME),
  CONSTRAINT KIL_SCHALTER_NAME_CK CHECK (REGEXP_LIKE(NAME, '^[a-z0-9_]+(\.[a-z0-9_]+)+$'))
)
/

CREATE TABLE KIL_PROTOKOLL (
  PROTOKOLL_ID    NUMBER(10)        NOT NULL,
  SITZUNG_ID      NUMBER(10)        NOT NULL,
  ZEIT            TIMESTAMP(6)      DEFAULT LOCALTIMESTAMP NOT NULL,
  SEKUNDE         NUMBER(9,1)       NOT NULL,
  ART             VARCHAR2(12)      NOT NULL,
  ZIEL            VARCHAR2(80 CHAR),
  TEXT            VARCHAR2(400 CHAR),
  SZENE_TAG       NUMBER(3),
  SZENE_STUNDE    NUMBER(5,2),
  GEOM            MDSYS.SDO_GEOMETRY,
  CONSTRAINT KIL_PROTOKOLL_PK PRIMARY KEY (PROTOKOLL_ID),
  CONSTRAINT KIL_PROTOKOLL_SITZUNG_FK FOREIGN KEY (SITZUNG_ID) REFERENCES KIL_SITZUNG (SITZUNG_ID) ON DELETE CASCADE,
  CONSTRAINT KIL_PROTOKOLL_ART_CK CHECK (ART IN ('START','ENDE','FEHLER','WARNUNG','INFO','ANSICHT','DREHBUCH','RUNDFLUG',
                                                 'AUSBRUCH','FOTO','EINRICHTER','DATENBANK')),
  CONSTRAINT KIL_PROTOKOLL_TAG_CK CHECK (SZENE_TAG IS NULL OR SZENE_TAG BETWEEN 1 AND 365),
  CONSTRAINT KIL_PROTOKOLL_STUNDE_CK CHECK (SZENE_STUNDE IS NULL OR (SZENE_STUNDE >= 0 AND SZENE_STUNDE < 24))
)
/

